import argparse
import hashlib
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

from pydantic import BaseModel
from sqlalchemy import Connection, create_engine, text

from inquest.settings import Settings
from inquest.synthetic.generator import GENERATOR_VERSION, generate
from inquest.synthetic.models import GeneratorConfig, World


def describe(world: World) -> str:
    config = world.config
    checksum = hashlib.sha256(world.model_dump_json().encode()).hexdigest()
    total = len(world.transactions)
    fraud_count = sum(label.is_fraud for label in world.truth)
    fraud = Counter(label.scenario for label in world.truth if label.is_fraud)
    fraud_episodes = {label.episode_id for label in world.truth if label.is_fraud}
    lookalikes = Counter(
        label.scenario
        for label in world.truth
        if label.episode_id is not None and label.episode_id not in fraud_episodes
    )
    channels: Counter[str] = Counter()
    channel_fraud: Counter[str] = Counter()
    missing_location: Counter[str] = Counter()
    weeks: dict[int, Counter[str]] = defaultdict(Counter)
    for transaction, label in zip(world.transactions, world.truth, strict=True):
        channel = transaction.channel
        channels[channel] += 1
        channel_fraud[channel] += int(label.is_fraud)
        missing_location[channel] += int(transaction.city_id is None)
        week = (transaction.occurred_at - config.start).days // 7 + 1
        weeks[week][channel] += 1
        weeks[week]["fraud"] += int(label.is_fraud)

    lines = [
        "# Synthetic dataset summary",
        "",
        "Generated by the Phase 1 fixture CLI using `fixtures/india.json`.",
        "Counts describe a synthetic fixture and its injected labels.",
        "",
        f"- Generator version {GENERATOR_VERSION}, seed {config.seed}, currency {config.currency}",
        f"- SHA-256 `{checksum}`",
        f"- {len(world.model_dump_json().encode()):,} bytes in canonical JSON",
        f"- {len(config.cities)} cities, {len(world.customers)} customers, "
        f"{len(world.merchants)} merchants and {len(world.devices)} devices",
        f"- {total:,} attempts, {fraud_count:,} fraudulent ({fraud_count / total:.3%})",
        f"- {world.transactions[0].occurred_at.isoformat()} through "
        f"{world.transactions[-1].occurred_at.isoformat()}",
        "",
        "| Channel | Attempts | Fraud | Missing physical location |",
        "| --- | ---: | ---: | ---: |",
    ]
    lines.extend(
        f"| {channel} | {channels[channel]:,} | {channel_fraud[channel]:,} | "
        f"{missing_location[channel]:,} ({missing_location[channel] / channels[channel]:.1%}) |"
        for channel in sorted(channels)
    )
    lines.extend(
        [
            "",
            "| Scenario | Fraud attempts | Attempts in legitimate lookalike episodes |",
            "| --- | ---: | ---: |",
        ]
    )
    lines.extend(
        f"| {scenario} | {fraud[scenario]:,} | {lookalikes[scenario]:,} |"
        for scenario in sorted(key for key in fraud.keys() | lookalikes.keys() if key is not None)
    )
    lines.extend(["", "| Week | Card | UPI | Fraud |", "| ---: | ---: | ---: | ---: |"])
    lines.extend(
        f"| {week} | {counts['card']:,} | {counts['upi']:,} | {counts['fraud']:,} |"
        for week, counts in sorted(weeks.items())
    )
    return "\n".join(lines) + "\n"


def insert_rows(
    connection: Connection,
    table: str,
    dataset_id: str,
    records: tuple[BaseModel, ...],
) -> None:
    # Table and field names come from the fixed importer mapping and model definitions.
    if not records:
        return
    columns = ("dataset_id", *type(records[0]).model_fields)
    names = ", ".join(columns)
    placeholders = ", ".join(f":{column}" for column in columns)
    statement = text(f"INSERT INTO {table} ({names}) VALUES ({placeholders})")
    for start in range(0, len(records), 1_000):
        rows: list[dict[str, Any]] = [
            {"dataset_id": dataset_id, **record.model_dump()}
            for record in records[start : start + 1_000]
        ]
        connection.execute(statement, rows)


def load_fixture(world: World, database_url: str) -> str:
    checksum = hashlib.sha256(world.model_dump_json().encode()).hexdigest()
    dataset_id = f"v{GENERATOR_VERSION}-{checksum}"
    engine = create_engine(database_url)
    try:
        with engine.begin() as connection:
            created = connection.execute(
                text("""
                    INSERT INTO fixture.datasets (id, seed, manifest)
                    VALUES (:id, :seed, CAST(:manifest AS jsonb))
                    ON CONFLICT (id) DO NOTHING RETURNING id
                """),
                {
                    "id": dataset_id,
                    "seed": world.config.seed,
                    "manifest": world.config.model_dump_json(),
                },
            ).scalar_one_or_none()
            if created is not None:
                for table, records in (
                    ("fixture.cities", world.config.cities),
                    ("fixture.customers", world.customers),
                    ("fixture.merchants", world.merchants),
                    ("fixture.devices", world.devices),
                    ("fixture.transactions", world.transactions),
                    ("evaluation.truth", world.truth),
                ):
                    insert_rows(connection, table, dataset_id, records)
    finally:
        engine.dispose()
    return dataset_id


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate a deterministic synthetic payment fixture"
    )
    parser.add_argument("--config", type=Path, default=Path("fixtures/india.json"))
    parser.add_argument("--report", type=Path)
    parser.add_argument(
        "--load", action="store_true", help="Import using the migration database role"
    )
    args = parser.parse_args()
    config = GeneratorConfig.model_validate_json(args.config.read_text())
    world = generate(config)
    if args.report:
        args.report.write_text(describe(world))
    if args.load:
        dataset_id = load_fixture(world, Settings().migration_database_url)
        print(f"Loaded fixture {dataset_id}")
    if not args.report and not args.load:
        print(describe(world), end="")


if __name__ == "__main__":
    main()
